/**
 * @brief 根据 PT100 电阻值计算温度。
 * @param fR PT100 电阻值，单位欧姆。
 * @return 温度值，单位摄氏度；-1 表示低于表格范围，-2 表示高于表格范围。
 *
 * 查找流程：
 *   1. 先判断是否超出 RTD_TAB_PT100 覆盖范围；
 *   2. 使用二分法找到 fR 所在的两个表格点；
 *   3. 在两个表格点之间做线性插值，得到更平滑的温度值。
 */
float CalculateTemperature(float fR)
{
    float fTem;
    float fLowRValue;
    float fHighRValue;
    int iTem;
    unsigned char i;
    unsigned char cBottom, cTop;

    /* 低于 -200℃ 对应电阻值，认为超下限。 */
    if (fR < RTD_TAB_PT100[0])
    {
        return -1;
    }

    /* 高于 850℃ 对应电阻值，认为超上限。 */
    if (fR > RTD_TAB_PT100[210])
    {
        return -2;
    }

    /* 二分查找的上下边界。 */
    cBottom = 0;
    cTop = 210;

    /*
     * 通过二分法寻找相邻两个表格点：
     *   cBottom 对应低端电阻；
     *   cTop    对应高端电阻。
     * 当二者只相差 1 时，fR 就落在这个 5℃ 区间内。
     */
    for (i = 105; (cTop - cBottom) != 1;)
    {
        if (fR < RTD_TAB_PT100[i])
        {
            cTop = i;
            i = (cTop + cBottom) / 2;
        }
        else if (fR > RTD_TAB_PT100[i])
        {
            cBottom = i;
            i = (cTop + cBottom) / 2;
        }
        else
        {
            /* 恰好命中表格点时，不需要插值，直接返回对应温度。 */
            iTem = (unsigned int)i * 5 - 200;
            fTem = (float)iTem;
            return fTem;
        }
    }

    iTem = (unsigned int)i * 5 - 200;
    fLowRValue = RTD_TAB_PT100[cBottom];
    fHighRValue = RTD_TAB_PT100[cTop];
    /* 在相邻两个 5℃ 表格点之间做线性插值。 */
    fTem = (((fR - fLowRValue) * 5) / (fHighRValue - fLowRValue)) + iTem;

    return fTem;
}

/**
 * @brief 将一次温度 ADC 原始值转换为温度并加入累计值。
 * @param raw_adc PT100 分压点 ADC 原始码值。
 *
 * 分压电路按原工程公式计算：
 *   tempV = raw_adc / 4096 * 3300mV
 *   Rpt   = 150 * tempV / (3300 - tempV)
 * 这里的 150 是分压电阻阻值，单位欧姆。
 */
void BspTemperature_Accumulate(uint16_t raw_adc)
{
    /* 使用原工程整数形式保留行为一致性，结果单位 mV。 */
    float tempV = (float)(raw_adc * 3300 / 4096);
    float Rpt = 150 * tempV / (3300 - tempV);

    MotoTempAdd = MotoTempAdd + CalculateTemperature(Rpt);
}

/**
 * @brief 温度平均滤波计时。
 *
 * 每调用 10000 次，把 MotoTempAdd 的平均值写入 SafeTemp，然后清零累计值。
 * 该函数在 ADC 控制周期末尾调用，因此平均窗口长度等于 10000 个控制周期。
 */
void BspTemperature_FilterTick(void)
{
    static uint16_t Temp_time_count;

    /* 在第 10000 次样本到达时更新平均温度。 */
    if (Temp_time_count == 9999)
    {
        SafeTemp = MotoTempAdd / 10000;
        MotoTempAdd = 0;
    }

    /* 计数器循环到 10000 后归零，开始下一轮平均窗口。 */
    Temp_time_count++;
    if (Temp_time_count == 10000)
    {
        Temp_time_count = 0;
    }
}
