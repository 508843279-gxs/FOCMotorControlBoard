/**
 * @file bsp_temperature.c
 * @brief PT100 温度换算与平均滤波。
 *
 * ADC 采样得到 PT100 分压点电压后，本模块先根据分压公式反推出 PT100
 * 电阻值，再通过 RTD_TAB_PT100 查表和线性插值计算温度。为了避免单次
 * ADC 噪声误触发过温保护，温度会先累加，之后每 10000 个控制周期更新
 * 一次 SafeTemp。
 */

/* 温度累计值，仅本模块内部使用。 */
static float MotoTempAdd;
/* 过滤后的安全温度值，保护模块通过 bsp.h 中的 extern 读取。 */
